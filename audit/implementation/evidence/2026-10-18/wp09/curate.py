"""Curate accepted WP09 evidence and verify the shipped stdlib report command."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import time

target = Path("audit/implementation/evidence/2026-10-18/wp09")
target.mkdir(parents=True, exist_ok=False)
original = Path("environment/h1-v2/wp09")
readable = Path("environment/h1-v2/wp09-report-format-v2")
mapping = []


def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def copy(source, name):
    destination = target / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    assert not destination.exists(), destination
    shutil.copyfile(source, destination)
    assert digest(source) == digest(destination)
    mapping.append({"original_path": str(source), "archive_path": str(destination),
                    "bytes": destination.stat().st_size, "sha256": digest(destination)})


copy(Path(".superpowers/sdd/2026-10-16-selective-tree-neurons-evidence/scientific-wp09-report.md"), "technical-report-v1.md")
copy(Path("artifacts/h1-v2/wp09-report-format-v2/reader-report-1.md"), "report.md")
copy(readable / "render_report.py", "render_report.py")
for p in sorted((readable / "report-inputs").iterdir()):
    if p.is_file():
        copy(p, "report-inputs/" + p.name)
for name in (
    "raw_audit.py", "clean_replay.py", "saved_state_comparison.py", "prepare_clean.py",
    "appendix-invocations.json", "appendix-math.stdout", "appendix-math.stderr",
    "appendix-score.stdout", "appendix-score.stderr", "raw-audit-invocation.json",
    "raw-audit.stdout", "raw-audit.stderr", "clean-replay-invocation.json",
    "clean-replay.stdout", "clean-replay.stderr", "saved-state-invocation.json",
    "replay-resource-observation.json", "report-rebuild.json", "renderer-preflight-error.json",
    "render_report-syntax-failed.py", "inventory.json",
):
    copy(original / name, "execution/" + name)
for name in ("inventory.json", "render-manifest.json", "format-report.md", "config.json"):
    p = readable / name
    if p.exists():
        copy(p, "presentation/" + name)
for p in sorted((original / "install-metadata").rglob("*")):
    if p.is_file():
        copy(p, "execution/install-metadata/" + str(p.relative_to(original / "install-metadata")))
for name in ("inventory-verification.json", "source-verification.json", "format-verification.json"):
    copy(Path(__file__).parent / name, "root/" + name)
copy(Path(__file__), "curate.py")

# Preserve exact generated bytes; no manual score editing.
shutil.copyfile(target / "report.md", "reports/final.md")
assert digest(Path("reports/final.md")) == "4b26c13d7d171f466d2305a471ac7c8781e2dd7eadcdad918fb72473cbd11d38"
output = Path("/private/tmp/tree-neuron-report-root-20261018.md")
assert not output.exists(), output
command = [sys.executable, str(target / "render_report.py"), str(output)]
start = time.perf_counter()
result = subprocess.run(command, capture_output=True, text=True)
receipt = {"scope": "Published stdlib-only report command from curated location",
           "command": command, "exit_code": result.returncode, "stdout": result.stdout,
           "stderr": result.stderr, "seconds": time.perf_counter() - start,
           "same_bytes_as_reports_final": result.returncode == 0 and output.read_bytes() == Path("reports/final.md").read_bytes(),
           "report_sha256": digest(Path("reports/final.md"))}
assert receipt["same_bytes_as_reports_final"], receipt
receipt_path = Path(__file__).parent / "published-report-verification.json"
receipt_path.write_text(json.dumps(receipt, indent=2) + "\n")
copy(receipt_path, "root/published-report-verification.json")

